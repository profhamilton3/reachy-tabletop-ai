"""Generate data/calibration/stereo_params.json from the versioned physical profile (#28 A).

The source of truth is calibration/reachy12_stereo_2026_08_27.json (#33 / PR #34). This is
NOT generated from the historical npz, which is rejected as physically impossible. Output
follows data/calibration/stereo_params_template.json (the file config.STEREO_CALIBRATION_PATH
points at), with the image size of the stored 480x640 frame and the profile's id and zoom.

    python scripts/generate_stereo_params.py            # write data/calibration/stereo_params.json
    python scripts/generate_stereo_params.py --check    # exit 1 if the committed file is out of date
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / "calibration" / "reachy12_stereo_2026_08_27.json"
OUTPUT = ROOT / "data" / "calibration" / "stereo_params.json"
RMS_PX = {"left": 0.97, "right": 0.84}   # 2026-08-27 intrinsics solve, as recorded in the profile provenance


def eye(profile, name):
    k, d = profile[name]["K"], profile[name]["dist"]
    return {"fx": k[0][0], "fy": k[1][1], "cx": k[0][2], "cy": k[1][2], "distortion": d}


def params_from_profile(profile):
    """Template-shaped stereo_params from a reachy_stereo_physical profile (plain data, no OpenCV needed)."""
    if profile.get("format") != "reachy_stereo_physical":
        raise ValueError("not a reachy_stereo_physical profile")
    width, height = profile["image_size"]
    return {
        "_note": "Generated by scripts/generate_stereo_params.py from calibration/" + PROFILE.name
                 + ". Do not edit; regenerate. Valid at the profile's zoom only.",
        "source_profile": profile["id"],
        "baseline_m": profile["baseline_m"],
        "image_width": width,
        "image_height": height,
        "camera_left": eye(profile, "left"),
        "camera_right": eye(profile, "right"),
        "R": profile["R"],
        "T": profile["T"],
        "zoom_level": profile.get("zoom_level"),
        "zoom_caveat": profile.get("zoom_caveat"),
        "calibrated_at": profile["provenance"]["date_derived"],
        "rms_error_px": RMS_PX,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", default=str(PROFILE))
    parser.add_argument("--output", default=str(OUTPUT))
    parser.add_argument("--check", action="store_true", help="compare with the existing file instead of writing")
    args = parser.parse_args()
    params = params_from_profile(json.loads(Path(args.profile).read_text()))
    out = Path(args.output)
    if args.check:
        current = json.loads(out.read_text()) if out.exists() else None
        print("up to date" if current == params else f"{out} is out of date; run without --check")
        return 0 if current == params else 1
    out.write_text(json.dumps(params, indent=2) + "\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
